;================================================================================
; function to plot dots on a bitplane
;================================================================================

;---------- Const ----------
; largeur effective (LE) = (DDFSTOP-DDFSTART)*2+16 == 320/8
NB_BPLS   = 2
W         = 320
H         = 256
BPL_SIZE  = W/8                                                                  ; if non IL W/8*H         ; if IL : W/8 
LINE_SIZE = W/8*NB_BPLS                                                          ; if non IL W/8           ; if IL : W/8*NB_BPLS
MODULO    = W/8*NB_BPLS-320/8                                                    ; if non IL : W/8 - LE/8  ; if IL : W/8*NB_BPLS-LE/8


;--------------------------------------------------------------------------------
; main
;--------------------------------------------------------------------------------
run:       
            lea        CUSTOM,a6
            move.w     #$8380,DMACON(a6)                                         ; enable copper + bitplane
            bsr        init_bpls
            bsr        init_copper
            move.l     #copper,COP1LC(a6)                                        ; set new copper
            move.w     #$0,COPJMP1(a6)                                           ; activate copper


main_loop:
            move.w     #$50,d1
            bsr        wait_raster
            move.w     #$004,COLOR00(a6)
            bsr        clear_bpls
            move.w     #$044,COLOR00(a6)
            bsr        plot_wave
            move.w     #$000,COLOR00(a6)

    		; mouse test
            btst       #6,$bfe001
            bne.b      main_loop
            rts

;--------------------------------------------------------------------------------
; init
;--------------------------------------------------------------------------------

init_copper:
            rts

init_bpls:
            move.l     #bpls,d0
            lea        copper_bpls,a0
            moveq      #NB_BPLS-1,d2
.init_copper_bpl:
            move.w     d0,6(a0)
            swap       d0
            move.w     d0,2(a0)
            swap       d0
            add.l      #8,a0
            add.l      #BPL_SIZE,d0
            dbf        d2,.init_copper_bpl
            rts

;--------------------------------------------------------------------------------
; misc
;--------------------------------------------------------------------------------

clear_bpls:
            lea        bpls,a0
            move.w     #W/32*H*NB_BPLS-1,d0
.clear_loop:
            clr.l      (a0)+
            dbf        d0,.clear_loop
            rts

plot_wave:
            ; draw circle
            lea        bpls,a0
            lea        sin1,a1
            move.w     pos_sin1_x,d3                                             ;x idx
            move.w     pos_sin1_y,d4                                             ;x idx
            add.w      #4,d3
            add.w      #2,d4
            and.w      #(NB_SIN1*2)-1,d3
            and.w      #(NB_SIN1*2)-1,d4
            move.w     d3,pos_sin1_x
            move.w     d4,pos_sin1_y
            move       #1,d2                                                     ; set color

            move.w     #32-1,d7                                                  ; nb dots
.loop1:
            move.w     (a1,d3),d0                                                ; set x coordinate
            move.w     (a1,d4),d1                                                ; set x coordinate
            bsr        plot_dot
            add        #1,d2
            cmp        #4,d2
            bne.b      .skip_reset
            move       #1,d2
.skip_reset:

            add.w      #2,d3
            add.w      #4,d4
            and.w      #(NB_SIN1*2)-1,d3
            and.w      #(NB_SIN1*2)-1,d4
            dbf        d7,.loop1
            rts

;a0: bpls, d0:x, d1:y, d2: color
plot_dot:
            movem.l    d0-d4/a0,-(a7)
            mulu.w     #LINE_SIZE,d1
            add.w      d1,a0
            move.w     d0,d3
            lsr.w      #3,d0
            add.w      d0,a0
            and.w      #7,d3
            eor.w      #7,d3
            ; need to figure out in which bitplane we want to set the bit
            moveq      #NB_BPLS-1,d4
.plot_in_bpl:
            lsr.b      #1,d2
            bcc        .not_in_bpl
            bset       d3,(a0)
.not_in_bpl:
            add.l      #BPL_SIZE,a0
            dbf        d4,.plot_in_bpl
            movem.l    (a7)+,d0-d4/a0
            rts

;--------------------------------------------------------------------------------
